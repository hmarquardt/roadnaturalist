import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await (await browser.newContext()).newPage();
const errors = [];
const rawCells = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
page.on('request', request => { if (/\/(national\/roads|national\/wetlands|national\/hydro)\//.test(request.url())) rawCells.push(request.url()); });
await page.goto('https://roadnaturalist.com', { waitUntil: 'domcontentloaded' });
await page.locator('#discover-roads').waitFor({ state: 'visible', timeout: 180000 });
await page.locator('#discovery-place').fill('princeton in');
await page.locator('#discovery-place-results .discovery-place-option').first().waitFor({ timeout: 120000 });
await page.locator('#discovery-place-results .discovery-place-option').first().click();
await page.locator('#discovery-radius-input').fill('25');
await page.locator('#discovery-radius-input').press('Enter');
await page.locator('#discover-roads').click();
await page.locator('#discovery-results tbody tr').first().waitFor({ timeout: 600000 });
console.log('LEAFLET', await page.evaluate(() => typeof globalThis.L?.map === 'function'));
console.log('TILES', await page.locator('#map .leaflet-tile-pane img').count());
console.log('CANDIDATE_PATHS', await page.locator('#map .leaflet-overlay-pane path').count());
console.log('ATTRIBUTION', (await page.locator('#map .leaflet-control-attribution').innerText()).slice(0, 60));
const before = await page.evaluate(() => JSON.stringify(globalThis.__rnMapBounds ?? null));
await page.locator('#discovery-results tbody tr').nth(2).locator('.discovery-row').click();
await page.waitForTimeout(1200);
const selectedList = await page.locator('#discovery-results tbody tr.selected .discovery-row').innerText();
const emphasised = await page.locator('#map path.leaflet-interactive').count();
console.log('LIST_SELECTION', selectedList.slice(0, 30), 'PATHS', emphasised);
await page.locator('#map').click({ position: { x: 300, y: 260 } });
await page.waitForTimeout(800);
console.log('MAP_CLICK_SELECTED', (await page.locator('#discovery-results tbody tr.selected .discovery-row').innerText().catch(() => 'none')).slice(0, 30));
console.log('RAW_CELLS', rawCells.length, 'ERRORS', errors.slice(0, 3));
void before;
await browser.close();
